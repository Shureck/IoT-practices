function partSection(): string {
  const cats = ['Плата', 'Основное', 'Датчики', 'Исполнители', 'Дисплеи', 'Связь и отладка'];
  const out: string[] = [];
  for (const cat of cats) {
    const defs = Object.values(DEFS).filter((d) => d.category === cat);
    if (!defs.length) continue;
    out.push(`### ${cat}`);
    for (const d of defs) {
      out.push(`#### ${d.title} — \`${d.type}\``, '', d.description, '');
      const pins = d.pins.filter((p) => p.kind !== undefined || d.type !== 'breadboard');
      if (d.type === 'breadboard') {
        out.push('Выводы: `a1`…`j30` (30 столбцов, ряды a–e соединены между собой в каждом столбце, f–j — тоже) и четыре шины питания `tn1`…`tn30`, `tp1`…`tp30`, `bp1`…`bp30`, `bn1`…`bn30` (без каждого 6-го отверстия). Деталь можно воткнуть в макетку, совместив координаты выводов.', '');
      } else if (d.type === 'esp32') {
        out.push('Выводы — в таблице «Плата ESP32» ниже.', '');
      } else {
        out.push(`Выводы (имя → смещение от первого вывода): ${pins.map((p) => `\`${p.name}\` (${p.x}, ${p.y}${p.kind ? `, ${p.kind}` : ''})`).join(', ')}.`, '');
      }
      if (d.props.length) out.push(...propRows(d.props), '');
      else out.push('Свойств нет.', '');
    }
  }
  return out.join('\n');
}

function propRows(props: PropDef[]): string[] {
  const rows = props.map((p) => {
    const kind = p.type === 'select' ? (p.options ?? []).map((o) => `\`${o.value}\``).join(' · ') : p.type === 'number' ? `число${p.min !== undefined ? ` ${p.min}…${p.max ?? ''}` : ''}${p.unit ? ` ${p.unit}` : ''}` : p.type === 'bool' ? 'true / false' : 'текст';
    return `| ${code(p.key)} | ${esc(p.label)} | ${esc(kind)} | ${esc(String(p.default))} | ${p.live ? 'да' : ''} |`;
  });
  return ['| Свойство (`props`) | Что это | Значения | По умолч. | «Ручка» в симуляции |', '|---|---|---|---|---|', ...rows];
}

function espSection(): string {
  const esp = DEFS.esp32;
  const rows = esp.pins.map((p) => `| ${code(p.name)} | ${p.gpio ?? ''} | ${esp.pins.indexOf(p) < 15 ? 'верхний' : 'нижний'} ряд | ${p.x}, ${p.y} | ${esc(p.label ?? p.kind ?? '')} |`);
  return ['| Вывод | GPIO | Ряд | x, y | Назначение |', '|---|---|---|---|---|', ...rows].join('\n');
}

function apiSection(): string {
  const out: string[] = [];
  for (const g of API_GROUPS) {
    out.push(`#### ${g.icon} ${g.title}`, '');
    for (const d of Object.values(g.items)) out.push(`- \`${d.sig}\` — ${esc(d.text)}`);
    out.push('');
  }
  const documented = new Set(API_GROUPS.flatMap((g) => Object.keys(g.items)));
  const rest = Object.keys(FUNCS).filter((n) => !documented.has(n)).sort();
  out.push('#### Остальные поддерживаемые функции', '', rest.map((n) => `\`${n}\``).join(', '), '');
  const classes = Object.entries(CLASSES).map(([cls, m]) => `- **${cls}**: ${Object.keys(m.methods).sort().map((x) => `\`${x}\``).join(', ')}`);
  out.push('#### Классы и их методы', '', ...classes, '');
  out.push('#### Готовые объекты', '', Object.entries(GLOBAL_OBJECTS).map(([n, o]) => `\`${n}\` (${o.cls})`).join(', '), '');
  out.push('#### Константы', '', Object.keys(CONSTS).sort().map((c) => `\`${c}\``).join(', '), '');
  out.push('#### Поддерживаемые `#include`', '', [...KNOWN_HEADERS].sort().map((h) => `\`${h}\``).join(', '), '');
  return out.join('\n');
}

