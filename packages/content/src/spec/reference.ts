const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s: string) => `\`${s}\``;

function fieldRows(fields: Record<string, Field>): string {
  const rows = Object.entries(fields).map(([k, f]) => `| ${code(k)} | ${esc(describe(f.shape))} | ${f.required ? 'да' : 'нет'}${f.default ? ` (по умолч. ${esc(f.default)})` : ''} | ${esc(f.desc)} |`);
  return ['| Поле | Значение | Обяз. | Описание |', '|---|---|---|---|', ...rows].join('\n');
}

function valueDoc(s: Shape): string {
  if (s.t === 'obj') return fieldRows(s.fields);
  return `Значение: ${describe(s)}.`;
}

